CREATE TABLE parent_student_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_account_id BIGINT NOT NULL REFERENCES users(account_id),
    student_account_id BIGINT NOT NULL REFERENCES users(account_id),
    UNIQUE (parent_account_id, student_account_id),
    CHECK (parent_account_id <> student_account_id)
);
